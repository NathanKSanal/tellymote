import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

const here = path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, "$1"));
const root = path.resolve(here, "..");
const spec = JSON.parse(fs.readFileSync(path.join(here, "narration.json"), "utf8"));

const FPS = 30;
const LEAD = 0.45;
const TAIL = 0.55;

const scenes = [
  { key: "intro", vo: "vo1" },
  { key: "dashboard", vo: "vo2" },
  { key: "remote", vo: "vo3" },
  { key: "devices", vo: "vo4" },
  { key: "trust", vo: "vo5" },
  { key: "cta", vo: "vo6" },
];

const durationOf = (id) => {
  const file = path.join(root, "public", "vo", `${id}.mp3`);
  const out = execFileSync("ffprobe", [
    "-v",
    "error",
    "-show_entries",
    "format=duration",
    "-of",
    "default=noprint_wrappers=1:nokey=1",
    file,
  ]);
  return Number(String(out).trim());
};

let cursor = 0;
const rows = [];
for (const scene of scenes) {
  const vo = durationOf(scene.vo);
  const seconds = LEAD + vo + TAIL;
  const duration = Math.round(seconds * FPS);
  rows.push({
    key: scene.key,
    voFile: `${scene.vo}.mp3`,
    from: cursor,
    duration,
    voFrom: cursor + Math.round(LEAD * FPS),
    voFrames: Math.round(vo * FPS),
  });
  cursor += duration;
}

const total = cursor;
const body = `// Generated by scripts/make_timing.mjs from the measured voice-over files.
// Re-run it after scripts/make_vo.py so the picture always matches the narration.
export const FPS = ${FPS};
export const TOTAL_FRAMES = ${total};

export type SceneTiming = {
  key: string;
  voFile: string;
  from: number;
  duration: number;
  voFrom: number;
  voFrames: number;
};

export const TIMING: Record<string, SceneTiming> = {
${rows
  .map(
    (r) =>
      `  ${r.key}: { key: "${r.key}", voFile: "${r.voFile}", from: ${r.from}, duration: ${r.duration}, voFrom: ${r.voFrom}, voFrames: ${r.voFrames} },`,
  )
  .join("\n")}
};

export const ORDER = [${rows.map((r) => `"${r.key}"`).join(", ")}];
`;

fs.writeFileSync(path.join(root, "src", "timing.ts"), body);
console.log(`total ${(total / FPS).toFixed(2)}s (${total} frames at ${FPS}fps)`);
for (const r of rows) console.log(`${r.key.padEnd(10)} from ${(r.from / FPS).toFixed(2)}s  ${(r.duration / FPS).toFixed(2)}s`);

// Sidecar subtitles for the platforms that want a caption file.
const stamp = (seconds) => {
  const ms = Math.round(seconds * 1000);
  const h = String(Math.floor(ms / 3600000)).padStart(2, "0");
  const m = String(Math.floor((ms % 3600000) / 60000)).padStart(2, "0");
  const s = String(Math.floor((ms % 60000) / 1000)).padStart(2, "0");
  const r = String(ms % 1000).padStart(3, "0");
  return `${h}:${m}:${s},${r}`;
};

const lines = spec.lines;
const srt = rows
  .map((row, i) => {
    const start = row.voFrom / FPS;
    const end = (row.voFrom + row.voFrames) / FPS;
    return `${i + 1}\n${stamp(start)} --> ${stamp(end)}\n${lines[i].text}\n`;
  })
  .join("\n");

fs.writeFileSync(path.join(root, "public", "tellymote-promo.srt"), srt);
console.log("wrote public/tellymote-promo.srt");
